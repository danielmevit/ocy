// Regenerates the Ocy brand kit exports (PNG + vector PDF) from the approved SVG assets, then mirrors the whole
// kit to the owner's copy outside the repo.
//
//   NODE_PATH=<node_modules with playwright> node assets/brand-kit/tools/brand-kit.mjs [--mirror <dir>] [--store <dir>]
//
// Defaults: --mirror = <repo>/../../brand-kit, --store = <repo>/../../builds/store-0.2.2/store-logos (sibling folders of the
// repo in the project layout). Set OCY_WIN_FONTS to the Windows fonts folder if it is not at the WSL default.
//
// Playwright is not a repo dependency; point NODE_PATH at any node_modules that has it.
// Fonts: raster exports use Segoe UI when the Windows fonts folder is reachable. PDFs never use Segoe UI (it is a
// Microsoft font and a PDF would embed its glyphs); PDF text uses Ubuntu Sans / DejaVu Sans (free licences).
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, cpSync, existsSync } from 'node:fs';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const require = createRequire(join(process.env.NODE_PATH?.split(':')[0] || process.cwd(), 'x.js'));
const { chromium } = require('playwright');
const kit = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repo = resolve(kit, '../..');
const arg = (n, d) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : d; };
const mirror = arg('--mirror', resolve(repo, '../../brand-kit'));
const storeSrc = arg('--store', resolve(repo, '../../builds/store-0.2.2/store-logos'));

const C = {
  jade: '#2F7D62', fill: '#348267', pressed: '#266951', tint: '#A3C7B8', art: '#63A189', deep: '#14573E',
  outline: '#12382A', offwhite: '#F6F7F5', tile: '#F2F7F4', leaf: '#38A27A', pale: '#DCE9E4', paleLeaf: '#CFE3DA',
};
const G = 'linear-gradient(135deg, #4FA585 0%, #2F7D62 30%, #2A7259 60%, #1F5A46 100%)';

// ---- sources (copied, never redrawn) ----
const src = {
  'logo/ocy-sprout-light.svg': join(repo, 'assets/icons/brand/ocy-sprout-light.svg'),
  'logo/ocy-sprout-dark.svg': join(repo, 'assets/icons/brand/ocy-sprout-dark.svg'),
  'logo/ocy-sprout-light-dark-stem.svg': join(repo, 'docs/store/screenshots/sprout-light-dark-stem.svg'),
  'character/ocy-character.svg': join(repo, 'assets/illustrations/ocy-v1f/svg/blink-light-f1.svg'),
  'character/ocy-character-deep-approved-direction.svg': join(repo, 'docs/store/screenshots/ocy-char-deep.svg'),
};
for (const [to, from] of Object.entries(src)) { mkdirSync(dirname(join(kit, to)), { recursive: true }); copyFileSync(from, join(kit, to)); }
const svg = rel => readFileSync(join(kit, rel), 'utf8').replace(/<!--[\s\S]*?-->/g, '');
const sized = (s, px) => s.replace(/width="\d+" height="\d+"/, `width="${px}" height="${px}"`);

// White-tile logo mark (tile radius 27%, sprout 73%), as an SVG built from the dark-stem sprout's geometry.
const inner = svg('logo/ocy-sprout-light-dark-stem.svg').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
const markSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="100" height="100">
<rect width="100" height="100" rx="27" fill="${C.tile}"/>
<svg x="13.5" y="13.5" width="73" height="73" viewBox="0 3.2 32 32">${inner}</svg></svg>\n`;
writeFileSync(join(kit, 'logo/ocy-logo-mark.svg'), markSvg);
// Horizontal lockup: mark + live-text wordmark (no glyph outlines; font-family fallback list).
const FONT = `'Segoe UI', 'Ubuntu Sans', 'Noto Sans', 'DejaVu Sans', sans-serif`;
const lockup = (ink) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 330 100" width="330" height="100">
${markSvg.replace(/<svg xmlns[^>]*>/, '<g>').replace(/<\/svg>\n$/, '</g>')}
<text x="122" y="71" font-family="${FONT}" font-weight="600" font-size="72" fill="${ink}">Ocy</text></svg>\n`;
writeFileSync(join(kit, 'logo/ocy-lockup-on-dark.svg'), lockup('#F2F5F3'));
writeFileSync(join(kit, 'logo/ocy-lockup-on-light.svg'), lockup(C.deep));

// ---- tokens ----
mkdirSync(join(kit, 'color'), { recursive: true });
writeFileSync(join(kit, 'color/tokens.json'), JSON.stringify({ color: C, gradient: { g: G } }, null, 2) + '\n');
writeFileSync(join(kit, 'color/tokens.css'), `/* Ocy brand tokens (generated by tools/brand-kit.mjs) */\n:root {\n${Object.entries(C).map(([k, v]) => `  --ocy-${k.replace(/[A-Z]/g, m => '-' + m.toLowerCase())}: ${v};`).join('\n')}\n  --ocy-gradient-g: ${G};\n}\n`);
mkdirSync(join(kit, 'backgrounds'), { recursive: true });
writeFileSync(join(kit, 'backgrounds/gradient-g.css'), `/* Background G: diagonal mint-jade sweep */\nbackground: ${G};\n`);

// ---- rendering ----
const W = process.env.OCY_WIN_FONTS || '/mnt/c/Windows/Fonts';
const segoe = existsSync(join(W, 'seguisb.ttf')) ? `@font-face{font-family:"Segoe UI";font-weight:600;src:url(${pathToFileURL(join(W, 'seguisb.ttf')).href})}
@font-face{font-family:"Segoe UI";font-weight:400;src:url(${pathToFileURL(join(W, 'segoeui.ttf')).href})}` : '';
const browser = await chromium.launch();
async function shot(file, w, h, body, { pdf = false, transparent = true, css = '' } = {}) {
  const page = await browser.newPage({ viewport: { width: w, height: h } });
  const fontCss = pdf ? '' : segoe; // never embed Segoe UI in PDFs
  const fam = pdf ? `'Ubuntu Sans','DejaVu Sans',sans-serif` : FONT;
  await page.setContent(`<!doctype html><style>${fontCss} @page{size:${w}px ${h}px;margin:0} html,body{margin:0;width:${w}px;height:${h}px;overflow:hidden;background:transparent;font-family:${fam}} ${css}</style>${body}`);
  await page.evaluate(() => document.fonts.ready);
  const out = join(kit, file);
  mkdirSync(dirname(out), { recursive: true });
  if (pdf) await page.pdf({ path: out, width: `${w}px`, height: `${h}px`, printBackground: true, pageRanges: '1' });
  else await page.screenshot({ path: out, omitBackground: transparent });
  await page.close(); console.log(out);
}
const center = (inner, bg = 'transparent') => `<div style="width:100%;height:100%;display:grid;place-items:center;background:${bg}">${inner}</div>`;
const logos = {
  'ocy-sprout-light': svg('logo/ocy-sprout-light.svg'),
  'ocy-sprout-dark': svg('logo/ocy-sprout-dark.svg'),
  'ocy-sprout-light-dark-stem': svg('logo/ocy-sprout-light-dark-stem.svg'),
  'ocy-logo-mark': markSvg,
};
for (const [name, s] of Object.entries(logos)) {
  for (const px of [64, 128, 256, 512, 1024]) await shot(`logo/png/${name}-${px}.png`, px, px, center(sized(s, px)));
  await shot(`logo/pdf/${name}.pdf`, 512, 512, center(sized(s, 512)), { pdf: true });
}
for (const [name, ink, bg] of [['ocy-lockup-on-dark', '#F2F5F3', G], ['ocy-lockup-on-light', C.deep, C.offwhite]])
  for (const h of [100, 200, 400]) await shot(`logo/png/${name}-${h * 3.3}x${h}.png`, h * 3.3, h,
    `<div style="width:100%;height:100%;background:${bg}">${lockup(ink).replace('width="330" height="100"', `width="${h * 3.3}" height="${h}"`)}</div>`, { transparent: false });
const chars = { 'ocy-character': svg('character/ocy-character.svg'), 'ocy-character-deep-approved-direction': svg('character/ocy-character-deep-approved-direction.svg') };
for (const [name, s] of Object.entries(chars)) {
  for (const px of [256, 512, 1024]) await shot(`character/png/${name}-${px}.png`, px, px, center(sized(s, px)));
  await shot(`character/pdf/${name}.pdf`, 512, 512, center(sized(s, 512)), { pdf: true });
}
for (const [w, h] of [[3840, 2160], [1920, 1080]]) await shot(`backgrounds/gradient-g-${w}x${h}.png`, w, h, `<div style="width:100%;height:100%;background:${G}"></div>`, { transparent: false });

// Swatch sheet
const rows = [['jade', 'Brand jade (light theme accent)'], ['fill', 'Dark-theme fill'], ['pressed', 'Pressed state'], ['tint', 'Small text on dark'],
  ['art', 'Art green'], ['deep', 'Deep jade: logo outline, text on light'], ['outline', 'Character outline (slides)'], ['leaf', 'Sprout leaf'],
  ['pale', 'Face and leaf-crescent pale'], ['paleLeaf', 'Pale leaf tint'], ['tile', 'Logo tile'], ['offwhite', 'Off-white surface']];
const sw = `<div style="padding:40px;background:#FFFFFF;width:100%;height:100%;box-sizing:border-box;color:#1B2B25">
<div style="font-size:34px;font-weight:600;margin-bottom:24px">Ocy colours</div>
<div style="display:grid;grid-template-columns:repeat(4,1fr);gap:18px">${rows.map(([k, l]) => `<div><div style="height:110px;border-radius:14px;background:${C[k]};border:1px solid rgba(0,0,0,.08)"></div>
<div style="font-size:18px;font-weight:600;margin-top:8px">${C[k]}</div><div style="font-size:15px">${l}</div></div>`).join('')}</div>
<div style="height:120px;border-radius:14px;background:${G};margin-top:24px"></div><div style="font-size:15px;margin-top:8px">Background G: #4FA585 0%, #2F7D62 30%, #2A7259 60%, #1F5A46 100%</div></div>`;
await shot('color/swatches.png', 1200, 860, sw, { transparent: false });
await shot('color/swatches.pdf', 1200, 860, sw, { pdf: true });

// Do / don't examples (small PNGs)
const ex = (label, ok, inner, bg = C.offwhite) => `<div style="width:100%;height:100%;background:#FFFFFF;display:flex;flex-direction:column;align-items:center;justify-content:center;gap:10px">
<div style="width:160px;height:160px;border-radius:18px;background:${bg};display:grid;place-items:center">${inner}</div>
<div style="font-size:17px;font-weight:600;color:${ok ? '#2F7D62' : '#A4432A'}">${ok ? 'Do' : 'Don\'t'}: ${label}</div></div>`;
const L = sized(logos['ocy-sprout-light'], 110), D = sized(logos['ocy-sprout-dark'], 110);
const dd = [
  ['do-light-on-light', 'light sprout on light', true, L],
  ['do-dark-on-dark', 'dark sprout on dark', true, D, '#1F2A26'],
  ['dont-recolour', 'recolour', false, `<div style="filter:hue-rotate(160deg)">${L}</div>`],
  ['dont-stretch', 'stretch', false, `<div style="transform:scaleX(1.5)">${L}</div>`],
  ['dont-rotate', 'rotate', false, `<div style="transform:rotate(25deg)">${L}</div>`],
  ['dont-wrong-variant', 'light sprout on dark', false, L, '#1F2A26'],
];
for (const [f, l, ok, inner, bg] of dd) await shot(`usage/${f}.png`, 260, 220, ex(l, ok, inner, bg), { transparent: false });
await browser.close();

// Final Store art (box art, poster, app tiles) rendered by docs/store/screenshots/store-logos.mjs.
mkdirSync(join(kit, 'store'), { recursive: true });
for (const f of ['box-art-2160x2160.png', 'box-art-1080x1080.png', 'poster-art-1440x2160.png', 'poster-art-720x1080.png',
  'app-tile-300x300.png', 'app-tile-150x150.png', 'app-tile-71x71.png', 'logo-mark-1080.png'])
  if (existsSync(join(storeSrc, f))) copyFileSync(join(storeSrc, f), join(kit, 'store', f)); else console.warn('missing store art', f);

// Mirror the whole kit to the owner's copy.
cpSync(kit, mirror, { recursive: true });
console.log('mirrored to', mirror);
